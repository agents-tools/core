import AgentsCore
import AgentsManifest
import Foundation

extension InstructionOperations {
  /// Audits disk, state and upstream refs without fetching objects, creating locks or recovering transactions.
  /// Supply Codex's effective settings to include trusted project, profile or policy overrides.
  /// Without them, discovery uses top-level user configuration and defaults.
  public static func doctor(
    scope: InstallScope = .project, environment: RuntimeEnvironment = RuntimeEnvironment(),
    codexConfiguration: CodexInstructionConfiguration? = nil
  ) throws -> InstructionDoctorReport {
    let store = StateStore(scope: scope, environment: environment)
    let other = StateStore(scope: scope == .project ? .user : .project, environment: environment)
    func pendingRecovery(_ store: StateStore) -> InstructionDiagnostic {
      let recovery = FileTransaction.recoveryDiagnostic(store: store)
      return InstructionDiagnostic(
        kind: recovery.requiresOwner ? .unresolvedTransaction : .pendingRecovery,
        message: recovery.message,
        path: store.directory)
    }
    let otherSections: [LockedSection]? = try other.withReadLock(
      onPendingRecovery: { nil },
      {
        _ = try other.readDeclaration()
        return try other.readResolved().instructions.sections
      })
    let otherDiagnostics = otherSections == nil ? [pendingRecovery(other)] : []
    let root = scope == .project ? environment.projectDirectory : environment.homeDirectory
    return try store.withReadLock(
      onPendingRecovery: {
        InstructionDoctorReport(
          root: root, diagnostics: otherDiagnostics + [pendingRecovery(store)])
      },
      {
        let declaration = try store.readDeclaration()
        let lock = try store.readResolved()
        var diagnostics = otherDiagnostics
        func report(_ kind: InstructionDiagnostic.Kind, _ message: String, _ path: URL? = nil) {
          diagnostics.append(InstructionDiagnostic(kind: kind, message: message, path: path))
        }
        if !FileManager.default.fileExists(atPath: store.resolvedURL.path),
          !(declaration.instructions?.sections.isEmpty ?? true)
            || !(declaration.instructions?.chatgpt?.isEmpty ?? true)
        {
          report(
            .missingLock, "Instruction declaration has no lock; update can reconstruct it.",
            store.resolvedURL)
        }
        let sources = InstructionSources(store: store)
        let targets = InstructionTargets(store: store)
        var unchanged = true
        if scope == .project {
          let project = environment.projectDirectory.resolvingSymlinksInPath()
          let records =
            lock.instructions.sections + lock.instructions.chatgpt.values.flatMap(\.sections)
          var seen = Set<String>()
          for record in records
          where record.source == InstructionSources.own && seen.insert(record.path).inserted {
            let file = project.appendingPathComponent(record.path)
            let current = try FileSystem.readUnlessDenied(at: file)
            if current.map(Instructions.hash) != record.hash {
              unchanged = false
              report(
                .ownChanged,
                "Own instructions file changed since the lock; run 'agents update': \(record.name)",
                file)
            }
          }
        }
        let sections =
          unchanged
          ? try? sources.restore(
            lock.instructions.sections, sources: lock.sources, cachedOnly: true
          ).map(\.section) : nil
        // Targets already reported as unreadable; the Codex chain must not report them again.
        var unreadableTargets = Set<String>()
        for (key, target) in lock.instructions.targets.sorted(by: { $0.key < $1.key }) {
          do {
            let file = try InstructionLocations.file(for: key, store: store)
            let bytes: Data?
            do {
              bytes = try InstructionTargets.read(file)
            } catch {
              unreadableTargets.insert(file.resolvingSymlinksInPath().path)
              throw error
            }
            if target.import != nil {
              switch try Instructions.detectDrift(
                in: bytes ?? Data(), lockedBlockHash: target.blockHash)
              {
              case .clean: break
              case .missing: report(.missingTarget, "Claude import block is missing.", file)
              case .drifted: report(.drift, "Claude import block differs from its lock.", file)
              }
              continue
            }
            if let bytes, !Instructions.isOwned(bytes) {
              report(.foreignTarget, "Target file was not generated by agents.", file)
            } else if let bytes, Instructions.hash(bytes) != target.blockHash {
              report(.drift, "Generated instructions differ from their lock.", file)
            } else if bytes == nil {
              report(.missingTarget, "Generated instructions file is missing.", file)
            }
            if let sections {
              let directory = (key as NSString).deletingLastPathComponent
              let group = sections.filter { scope == .user || $0.directory == directory }
              if !group.isEmpty {
                let text = try Instructions.render(group)
                for problem in targets.linkProblems(in: text, file: file, key: key) {
                  report(.invalidLink, "Link '\(problem.destination)' \(problem.reason).", file)
                }
              }
            }
          } catch {
            report(.invalidTarget, "\(key): \(error)")
          }
        }
        if let otherSections {
          let duplicates = Instructions.sectionsInBothScopes(
            user: (scope == .user ? lock.instructions.sections : otherSections).map(
              InstructionSources.identity),
            project: (scope == .project ? lock.instructions.sections : otherSections).map(
              InstructionSources.identity))
          for id in duplicates {
            report(.duplicateScope, "Section is installed at both scopes: \(id)")
          }
        }
        let agents = Set(lock.instructions.targets.values.flatMap(\.agents))
          .union(declaration.instructions?.agents ?? declaration.defaultAgents)
        let claudeTargets = lock.instructions.targets.filter {
          $0.value.import == nil && $0.value.agents.contains(.claudeCode)
        }.keys.sorted()
        if scope == .project, !claudeTargets.isEmpty {
          do {
            let targets = InstructionTargets(store: store)
            let rootFiles = try targets.claudeFiles()
            if claudeTargets.contains("AGENTS.md"),
              case .needsImport(let path) = try ClaudeForwarding.classify(rootFiles)
            {
              report(
                .claudeForwarding, "Claude file does not forward to the project's AGENTS.md.",
                environment.projectDirectory.appendingPathComponent(path.rawValue))
            }
            // Claude Code reads a nested AGENTS.md only while no Claude file exists at the project
            // root or in its own directory, unless that directory's Claude file imports it.
            for key in claudeTargets where key != "AGENTS.md" {
              let directory = (key as NSString).deletingLastPathComponent
              let folder = environment.projectDirectory.appendingPathComponent(directory)
              let files = try targets.claudeFiles(in: folder)
              if case .needsImport(let path) = try ClaudeForwarding.classify(files) {
                report(
                  .claudeForwarding,
                  "Claude Code reads this file instead of \(key); import AGENTS.md from it.",
                  folder.appendingPathComponent(path.rawValue))
              } else if files.isEmpty, let hiding = rootFiles.first {
                report(
                  .claudeForwarding,
                  "Claude Code does not read \(key) while \(hiding.path.rawValue) exists at the project root; add a Claude file in \(directory) that imports AGENTS.md.",
                  folder.appendingPathComponent("AGENTS.md"))
              }
            }
          } catch { report(.claudeForwarding, "Cannot inspect Claude forwarding: \(error)") }
          let userClaude = InstructionLocations.file(
            for: .claudeCode, scope: .user, environment: environment)?.resolvingSymlinksInPath()
          for directory in InstructionDoctor.ancestors(of: environment.projectDirectory)
          where otherSections != nil {
            for path in ClaudeInstructionPath.allCases {
              let file = directory.appendingPathComponent(path.rawValue)
              if file.resolvingSymlinksInPath() != userClaude,
                FileManager.default.fileExists(atPath: file.path)
              {
                report(
                  .claudeAncestor,
                  "Ancestor Claude file can hide project AGENTS.md; it is outside this scope.", file
                )
              }
            }
          }
        }
        if agents.contains(.codex), scope == .user || otherSections != nil {
          diagnostics += InstructionDoctor.codex(
            scope: scope, environment: environment, lock: lock, configuration: codexConfiguration,
            reportedUnreadable: unreadableTargets)
        }
        diagnostics += InstructionSourceDiagnostics.inspect(
          store: store, declaration: declaration, lock: lock)
        return InstructionDoctorReport(
          root: root,
          diagnostics: diagnostics)
      })
  }

  /// Audits explicit project roots independently. An unreadable scope becomes a diagnostic;
  /// no project is repaired and no source cache is populated.
  public static func doctor(
    projectRoots: [URL], environment: RuntimeEnvironment = RuntimeEnvironment(),
    codexConfiguration: ((URL) throws -> CodexInstructionConfiguration)? = nil
  ) -> [InstructionDoctorReport] {
    var seen = Set<String>()
    return projectRoots.compactMap { root in
      let root = root.standardizedFileURL
      guard seen.insert(root.path).inserted else { return nil }
      var runtime = environment
      runtime.projectDirectory = root
      do {
        return try doctor(
          scope: .project, environment: runtime, codexConfiguration: codexConfiguration?(root))
      } catch {
        return InstructionDoctorReport(
          root: root,
          diagnostics: [
            InstructionDiagnostic(
              kind: .stateUnavailable, message: String(describing: error), path: root)
          ])
      }
    }
  }
}

private enum InstructionDoctor {
  static func ancestors(of root: URL) -> [URL] {
    var result: [URL] = []
    var cursor = root.resolvingSymlinksInPath()
    while cursor.path != "/" {
      cursor.deleteLastPathComponent()
      result.append(cursor)
    }
    return result
  }

  /// `reportedUnreadable` holds resolved paths the caller already reported as unreadable.
  static func codex(
    scope: InstallScope, environment: RuntimeEnvironment, lock: ResolvedState,
    configuration supplied: CodexInstructionConfiguration?,
    reportedUnreadable: Set<String> = []
  ) -> [InstructionDiagnostic] {
    var result: [InstructionDiagnostic] = []
    let user = InstructionLocations.file(for: .codex, scope: .user, environment: environment)!
    let config = user.deletingLastPathComponent().appendingPathComponent("config.toml")
    var configuration = supplied ?? CodexInstructionConfiguration()
    do {
      if supplied == nil, FileManager.default.fileExists(atPath: config.path) {
        configuration = try CodexInstructionConfiguration(FileSystem.read(at: config))
      }
    } catch {
      result.append(
        InstructionDiagnostic(
          kind: .invalidConfiguration,
          message: "Cannot read instruction discovery configuration: \(error)",
          path: config))
    }
    let store = StateStore(scope: scope, environment: environment)
    func managed(_ file: URL) -> Bool {
      lock.instructions.targets.contains { key, value in
        value.agents.contains(.codex)
          && (try? InstructionLocations.file(for: key, store: store))
            == InstructionLocations.physical(file)
      } || content(file).map(Instructions.isGenerated) == true
    }
    var unreadable = reportedUnreadable
    func content(_ file: URL) -> Data? {
      var isDirectory: ObjCBool = false
      guard FileManager.default.fileExists(atPath: file.path, isDirectory: &isDirectory),
        !isDirectory.boolValue
      else { return nil }
      do {
        return try FileSystem.readUnlessDenied(at: file) ?? Data()
      } catch {
        // The chain visits a file once per leaf and once for ownership; report it once.
        if unreadable.insert(file.resolvingSymlinksInPath().path).inserted {
          result.append(
            InstructionDiagnostic(
              kind: .invalidTarget, message: "Cannot read instructions: \(error)", path: file))
        }
        return Data()
      }
    }
    func blank(_ data: Data) -> Bool {
      String(decoding: data, as: UTF8.self).trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }
    // The user file is loaded separately, without a size limit; only an override can hide it.
    if scope == .user {
      let override = user.deletingLastPathComponent().appendingPathComponent("AGENTS.override.md")
      if let data = content(override), !blank(data), managed(user) {
        result.append(
          InstructionDiagnostic(
            kind: .codexOverride, message: "AGENTS.override.md hides a managed AGENTS.md.",
            path: override))
      }
      return result
    }
    // A project chain runs from the nearest root marker down to the working directory. The first
    // regular file per directory wins, even an empty one; whitespace-only files add nothing.
    let project = environment.projectDirectory.resolvingSymlinksInPath()
    var leaves = [project]
    for key in lock.instructions.targets.keys where key.hasSuffix("/AGENTS.md") {
      if let file = try? InstructionLocations.file(for: key, store: store) {
        leaves.append(file.deletingLastPathComponent())
      }
    }
    var hidden = Set<String>()
    for leaf in leaves {
      let candidates = [leaf] + ancestors(of: leaf)
      let root = candidates.firstIndex { directory in
        configuration.rootMarkers.contains {
          FileManager.default.fileExists(atPath: directory.appendingPathComponent($0).path)
        }
      }
      let chain = root.map { Array(candidates[...$0].reversed()) } ?? [leaf]
      var loaded: [(URL, Int)] = []
      for directory in chain {
        let names = ["AGENTS.override.md", "AGENTS.md"] + configuration.fallbackNames
        guard
          let (file, data) = names.lazy.compactMap({ name -> (URL, Data)? in
            let file = directory.appendingPathComponent(name)
            return content(file).map { (file, $0) }
          }).first
        else { continue }
        if file.lastPathComponent == "AGENTS.override.md",
          managed(directory.appendingPathComponent("AGENTS.md")),
          hidden.insert(file.path).inserted
        {
          result.append(
            InstructionDiagnostic(
              kind: .codexOverride, message: "AGENTS.override.md hides a managed AGENTS.md.",
              path: file))
        }
        if !blank(data) { loaded.append((file, data.count)) }
      }
      let bytes = loaded.reduce(0) { $0 + $1.1 }
      if bytes > configuration.maxBytes {
        result.append(
          InstructionDiagnostic(
            kind: .codexSize,
            message:
              "Codex project instructions are \(bytes) bytes, exceeding project_doc_max_bytes (\(configuration.maxBytes)): \(loaded.map { $0.0.path }.joined(separator: ", "))",
            path: leaf))
      }
    }
    return result
  }
}
