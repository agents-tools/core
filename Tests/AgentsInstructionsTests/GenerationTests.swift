import AgentsInstructions
import Foundation
import Testing

@Suite("Generated targets")
struct GenerationTests {
  @Test func rendersNoticeThenSectionsInOrder() throws {
    let one = try unit("---\ndescription: d\n---\n# One\nFirst.\n", id: "a:one")
    let two = try unit("---\ndescription: d\n---\n## Two\nSecond.\n", id: "a:two")
    let text = try Instructions.render([two, one])
    #expect(text == generated(["## Two\nSecond.", "# One\nFirst."]))
    #expect(Instructions.isGenerated(Data(text.utf8)))
    #expect(Instructions.isGenerated(Data([0xEF, 0xBB, 0xBF]) + Data(text.utf8)))
  }

  @Test func rejectsEqualHeadingsOnlyAtTheSameLevel() throws {
    let first = try unit("---\ndescription: d\n---\n# Rules\nA.\n", id: "a:one")
    let same = try unit("---\ndescription: d\n---\n#   Rules  \nB.\n", id: "a:two")
    let deeper = try unit("---\ndescription: d\n---\n## Rules\nC.\n", id: "a:three")
    #expect(
      throws: InstructionError.duplicateHeading(heading: "Rules", sectionIDs: ["a:one", "a:two"])
    ) {
      try Instructions.render([first, same])
    }
    #expect(throws: Never.self) { try Instructions.render([first, deeper]) }
    #expect(throws: InstructionError.invalidAssembly) { try Instructions.render([]) }
  }

  @Test(arguments: [
    "Owner text.\n", "", "<!-- Generated by agents -->\n",
    "\n" + Instructions.notice + "\n",
  ])
  func otherFilesAreNotGenerated(_ text: String) {
    #expect(!Instructions.isGenerated(Data(text.utf8)))
  }

  @Test func findsLocalLinksOutsideCode() {
    let text = """
      [Guide](docs/guide.md#start) and ![Logo](assets/logo%20mark.png?raw=1)
      [Web](https://example.com/a.md), [Anchor](#rules), [File](file:///etc/hosts)
      [Mail](mailto:team@example.com) `[Code](code.md)` <a href="raw.md">raw</a>

      [unused]: <notes/used.md>

      ```
      [Fenced](fenced.md)
      [defined]: fenced.md
      ```
      """
    let links = Instructions.localLinks(in: text)
    #expect(links.map(\.kind) == [.link, .image, .link, .html, .definition])
    #expect(
      links.compactMap(\.path) == [
        "docs/guide.md", "assets/logo mark.png", "/etc/hosts", "notes/used.md",
      ])
  }

  @Test func chatGPTPromptsKeepScopesAndAppendCustomBytes() throws {
    let scoped = try unit(
      "---\ndescription: d\npaths: [\"**/*.swift\"]\n---\n# Swift\nUse care.\n")
    let custom = Data("Custom\r\n".utf8)
    let rendered = try Instructions.renderChatGPT(sections: [scoped], customContent: custom)
    #expect(
      rendered
        == Data(
          "# Swift\n\nApplies when working on files matching `**/*.swift`.\n\nUse care.\n\n".utf8)
        + custom)
    #expect(throws: InstructionError.emptyPrompt) {
      try Instructions.renderChatGPT(sections: [])
    }
    #expect(throws: InstructionError.invalidUTF8) {
      try Instructions.renderChatGPT(sections: [scoped], customContent: Data([0xFF]))
    }
  }

  @Test func claudeImportDriftUsesTheManagedBlock() throws {
    let block = ClaudeForwarding.renderBlock(for: .root)
    let hash = "sha256:" + String(repeating: "0", count: 64)
    #expect(
      try Instructions.detectDrift(in: Data("Custom.\n".utf8), lockedBlockHash: hash) == .missing)
    #expect(
      try Instructions.detectDrift(in: Data(("Custom.\n\n" + block).utf8), lockedBlockHash: hash)
        == .drifted)
  }
}
