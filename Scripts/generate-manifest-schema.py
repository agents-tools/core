#!/usr/bin/env python3
"""Compile the finite field shapes used by the shipped manifest schema."""
import argparse,json,subprocess
from pathlib import Path
root=Path(__file__).resolve().parent.parent
source=root/'Sources/AgentsManifest/Resources/agents.schema.json'
schema=json.loads(source.read_text())
allowed={'$schema','$id','$defs','$ref','title','description','examples','type','properties','required','additionalProperties','items','enum','const','oneOf','minimum','maxItems','maxProperties','x-agents-scalar-kind','x-agents-native-value'}
def q(s):return json.dumps(s,ensure_ascii=False)
def emit(v):
 unknown=set(v)-allowed
 if unknown:raise ValueError('unsupported schema keywords: '+str(unknown))
 if '$ref' in v:return '.named('+q(v['$ref'].removeprefix('#/$defs/'))+')'
 if v.get('x-agents-native-value'):return '.native'
 if 'oneOf' in v:return '.oneOf(['+', '.join(emit(x) for x in v['oneOf'])+'])'
 if 'const' in v:return '.constant('+q(str(v['const']))+')' if isinstance(v['const'],str) else '.version'
 if 'enum' in v:return '.enumeration(['+', '.join(q(x) for x in v['enum'])+'])'
 kind=v['type']
 if kind=='string':return '.string'
 if kind=='integer':return '.integer(minimum: '+str(v.get('minimum',-9223372036854775808))+')'
 if kind=='array':return '.array('+emit(v['items'])+')'
 if kind=='object':
  if isinstance(v['additionalProperties'],dict):return '.dictionary('+emit(v['additionalProperties'])+')'
  props=', '.join(q(k)+': '+emit(x) for k,x in v.get('properties',{}).items())
  return '.object(['+props+'], required: ['+', '.join(q(x) for x in v.get('required',[]))+'])'
 raise ValueError('unsupported field shape '+kind)
text='// Generated by Scripts/generate-manifest-schema.py.\n\nenum ManifestSchema {\n  static let root: YAMLRule = '+emit(schema)+'\n  static let definitions: [String: YAMLRule] = [\n'
text+=''.join('    '+q(k)+': '+emit(v)+',\n' for k,v in schema['$defs'].items())+'  ]\n}\n'
text=subprocess.run(['xcrun','swift-format','format','--configuration',str(root/'.swift-format')],input=text,text=True,capture_output=True,check=True).stdout
path=root/'Sources/AgentsManifest/ManifestSchema.swift'
def describe(v):
 if '$ref' in v:return v['$ref'].removeprefix('#/$defs/')
 if v.get('x-agents-native-value'):return 'NativeValue'
 if 'const' in v:return '`'+str(v['const'])+'`'
 if 'enum' in v:return ' / '.join('`'+str(x)+'`' for x in v['enum'])
 if 'oneOf' in v:return 'one of: '+', '.join(describe(x) for x in v['oneOf'])
 if v.get('type')=='array':return 'sequence of '+describe(v['items'])
 if v.get('type')=='object':return 'name → '+describe(v['additionalProperties']) if isinstance(v.get('additionalProperties'),dict) else 'mapping'
 return v.get('type','value')
help='# Manifest Field Shapes\n\nGenerated from `Sources/AgentsManifest/Resources/agents.schema.json`.\n'
for name,definition in [('Declaration',schema)]+list(schema['$defs'].items()):
 help+='\n## '+name+'\n\n'
 if 'properties' in definition:
  help+='| Field | Required | Shape |\n| --- | --- | --- |\n'
  for key,value in definition['properties'].items():help+='| `'+key+'` | '+('yes' if key in definition.get('required',[]) else '')+' | '+describe(value)+' |\n'
 else:help+=describe(definition)+'\n'
help_path=root/'Documentation/Reference/ManifestSchema.md' 
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
if args.check:
 if not path.exists() or path.read_text()!=text or not help_path.exists() or help_path.read_text()!=help:raise SystemExit('generated manifest schema/help is stale')
else:
 path.write_text(text)
 help_path.write_text(help)
